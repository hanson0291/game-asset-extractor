import assert from 'node:assert/strict';
import * as THREE from '../vendor/modern/three.module.js';
import {createVehicleDriver} from '../vehicle-driving.js';
function setup(){const car=new THREE.Group();car.name='Vehicle: Drone Webb';car.userData.size={width:11,height:3,length:14};car.userData.vehicle={id:'drone-webb',family:'drone_webb',name:'Drone Webb'};return createVehicleDriver(car);}
const flight=setup();assert.equal(flight.kind,'airplane','Drone Webb jet uses the airplane controller');
const quad=(()=>{const car=new THREE.Group();car.name='Vehicle: Camera Drone';car.userData.size={width:1,height:.5,length:1};car.userData.vehicle={id:'camera-drone',family:'drone',name:'Camera Drone'};return createVehicleDriver(car);})();
assert.notEqual(quad.kind,'airplane','A plain quadcopter drone keeps the ground controller');
flight.start();
for(let i=0;i<120;i++)flight.update(1/60,{throttleInput:1});
assert.ok(flight.throttlePercent>95&&flight.enginePercent>95,'Throttle and engine spool up');
assert.ok(flight.speed>10&&flight.grounded,'Takeoff roll builds airspeed on the ground');
for(let i=0;i<600&&flight.grounded;i++)flight.update(1/60,{});
assert.ok(flight.takeoffReady,'Full throttle reaches rotate speed');
const startZ=flight.car.position.z;
for(let i=0;i<120;i++)flight.update(1/60,{pitch:1});
assert.equal(flight.grounded,false,'Pulling back at rotate speed lifts off');assert.ok(flight.altitude>3,'Climb gains altitude');
assert.ok(flight.car.position.z<startZ,'The aircraft moves forward through the air');
assert.ok(flight.nosePitch>5,'Nose rises while climbing');
const headingBefore=flight.heading;
for(let i=0;i<120;i++)flight.update(1/60,{roll:1,pitch:.3});
assert.ok(flight.bank>20,'Stick right banks the wings');
assert.ok(flight.heading>headingBefore,'Banked wings turn the aircraft');
for(let i=0;i<900&&!(flight.stalled&&flight.verticalSpeed<0);i++)flight.update(1/60,{pitch:1,throttleInput:-1});
assert.ok(flight.stalled,'Slow flight with the nose held up stalls');
assert.ok(flight.verticalSpeed<0,'A stalled aircraft sinks');
for(let i=0;i<1800&&!flight.grounded;i++)flight.update(1/60,{pitch:-.25,throttleInput:-1,brake:true});
assert.equal(flight.grounded,true,'Descending with power off lands the aircraft');assert.equal(flight.altitude,0);
for(let i=0;i<300;i++)flight.update(1/60,{brake:true});
assert.ok(flight.speed<2,'Wheel brakes stop the aircraft after touchdown');
flight.reset();assert.equal(flight.altitude,0);assert.equal(flight.speed,0);assert.equal(flight.throttlePercent,0);assert.equal(flight.car.rotation.y,0);
flight.start();for(let i=0;i<60;i++)flight.update(1/60,{throttleInput:1});
for(let i=0;i<2400&&flight.grounded;i++)flight.update(1/60,{});
for(let i=0;i<2400;i++)flight.update(1/60,{pitch:1});
assert.ok(flight.altitude<=150,'Ceiling is enforced');
const simulate=dt=>{const f=setup();f.start();for(let elapsed=0;elapsed<6-1e-5;elapsed+=dt)f.update(dt,{throttleInput:.8,pitch:.4,roll:.2});return f;};
assert.ok(simulate(1/30).car.position.distanceTo(simulate(1/60).car.position)<1e-6,'Flight is consistent at 30/60 FPS');
console.log('PASS: airplane detection, spool, takeoff roll, liftoff, climb, banked turn, stall, landing, brakes, reset, ceiling and frame-rate stability.');
